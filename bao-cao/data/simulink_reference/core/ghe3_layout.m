function layout = ghe3_layout(p)
%GHE3_LAYOUT Separate frame outline from lower/upper joint-center geometry.
% Top plate may be any rigid shape containing these three assumed CA centers.
% All lengths SI. Point-to-frame clearances are NOT assembly clearances.
p=ghe3_validate(p);
if ~isfield(p,'frameBaseSide') || ~isnumeric(p.frameBaseSide) || ...
 ~isscalar(p.frameBaseSide) || ~isfinite(p.frameBaseSide) || p.frameBaseSide<=0
 error('ghe3:frame','frameBaseSide must be a positive finite scalar.');
end
angles=(0:2)*2*pi/3;
if isfield(p,'legAngles'),angles=reshape(p.legAngles,1,3);end
baseAngles=angles+p.baseAngle;
[L,~,g]=ghe3_geometry([p.h0;0;0],p);
Rf=p.frameBaseSide/sqrt(3);
vertices=Rf*[cos(baseAngles);sin(baseAngles);zeros(1,3)];
L0=mean(L); % Actual neutral length implied by h0, not forced to half stroke.
layout=struct('units','SI','outerFrameSide',p.frameBaseSide, ...
 'outerFrameCircumradius',Rf,'outerFrameVertices',vertices, ...
 'baseAnchorRadius',p.rb,'baseAnchorSide',sqrt(3)*p.rb, ...
 'upperAnchorRadius',p.rp,'upperAnchorSide',sqrt(3)*p.rp, ...
 'basePoints',g.B,'topPointsBody',g.A,'topPointsNeutral',g.P, ...
 'lowerPinAxes',g.hingeAxes,'upperPinAxesBody', ...
 [-sin(angles+p.platformAngle);cos(angles+p.platformAngle);zeros(1,3)], ...
 'neutralLengths',L,'neutralHeight',p.h0, ...
 'halfStrokeReferenceLength',p.Lmin+p.stroke/2, ...
 'neutralBodyLean',atan2(abs(p.rb-p.rp),p.h0), ...
 'neutralBodyLeanFromLength',asin(min(1,abs(p.rb-p.rp)/L0)), ...
 'pointNormalFrameMargin',(Rf-p.rb)/2, ...
 'pointRadialFrameSetback',Rf-p.rb,'assemblyClearanceAssessed',false, ...
 'topPlateOutlineKnown',false,'safeDesignCertified',false);
layout.assumptions=['Outer frame and anchor triangles are centered, aligned ', ...
 'and equilateral. Upper radius 0.360m is assumed. The frame edge is not ', ...
 'a joint-center side. Lower CA pins are horizontal tangents. CA envelopes, ', ...
 'frame member widths, rod-end ratings and collisions remain unassessed.'];
end
